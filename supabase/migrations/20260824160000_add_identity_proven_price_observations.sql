create function public.record_identity_proven_price_observation(
  p_offer_id bigint,
  p_observation_kind text,
  p_source_run_id text,
  p_source_importer text,
  p_existing_history_id bigint default null
) returns jsonb
language plpgsql volatile security definer set search_path=pg_catalog,public,pg_temp as $recorder$
declare
  v_offer public.offers%rowtype;
  v_mapping public.retailer_products%rowtype;
  v_variant public.product_variants%rowtype;
  v_product public.products%rowtype;
  v_retailer public.retailers%rowtype;
  v_policy public.price_observation_producers%rowtype;
  v_identity jsonb;
  v_fingerprint text;
  v_series_id bigint;
  v_history_id bigint;
  v_gtin text;
  v_unit_count integer;
  v_unit_type text;
  v_flags text[]:='{}';
  v_previous public.price_history%rowtype;
  v_previous_two public.price_history%rowtype;
  v_status text;
begin
  if p_offer_id is null or p_offer_id<=0 then
    return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','INVALID_OFFER_ID');
  end if;
  if p_observation_kind not in ('offer_created','delivered_price_changed','daily_confirmation') then
    return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','UNSUPPORTED_OBSERVATION_KIND');
  end if;
  if p_source_run_id is null or p_source_run_id!~'^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'
     or p_source_importer is null or p_source_importer!~'^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$' then
    return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','INVALID_SOURCE_PROVENANCE');
  end if;

  select * into v_offer from public.offers where id=p_offer_id for update;
  if not found then return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','OFFER_NOT_FOUND'); end if;
  select * into v_policy from public.price_observation_producers where retailer_id=v_offer.retailer_id and source_importer=p_source_importer;
  if not found or not v_policy.enabled then
    return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','PRODUCER_DISABLED','retailer_id',v_offer.retailer_id::text,'source_importer',p_source_importer);
  end if;

  select * into v_mapping from public.retailer_products where id=v_offer.retailer_product_id;
  select * into v_variant from public.product_variants where id=v_offer.product_variant_id;
  select * into v_product from public.products where id=v_offer.product_id;
  select * into v_retailer from public.retailers where id=v_offer.retailer_id;
  if v_mapping.id is null or v_variant.id is null or v_product.id is null or v_retailer.id is null
     or not v_product.is_active or v_product.merged_into_product_id is not null or not v_variant.is_active
     or v_mapping.product_id is distinct from v_offer.product_id or v_mapping.retailer_id is distinct from v_offer.retailer_id
     or v_mapping.product_variant_id is distinct from v_offer.product_variant_id or v_variant.product_id is distinct from v_offer.product_id
     or nullif(trim(v_mapping.external_product_id),'') is null
     or v_variant.pack_count is null or v_variant.pack_count<=0
     or v_variant.size_value is null or v_variant.size_value<=0 or v_variant.size_value::text='NaN'
     or nullif(trim(v_variant.size_unit),'') is null then
    return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','MISSING_OR_CONFLICTING_EXACT_IDENTITY');
  end if;
  if v_offer.price is null or v_offer.price<=0 or v_offer.price::text='NaN'
     or v_offer.shipping_cost is null or v_offer.shipping_cost<0 or v_offer.shipping_cost::text='NaN'
     or v_offer.total_price is null or v_offer.total_price<=0 or v_offer.total_price::text='NaN'
     or round(v_offer.price+v_offer.shipping_cost,2) is distinct from round(v_offer.total_price,2)
     or v_offer.in_stock is null or v_offer.last_checked_at is null then
    return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','INCOMPLETE_DELIVERED_PRICE_OR_STOCK');
  end if;

  v_unit_count:=case when coalesce(v_product.unit_pricing_verified,false) and v_product.unit_count>0 and nullif(trim(v_product.unit_type),'') is not null then v_product.unit_count else null end;
  v_unit_type:=case when v_unit_count is not null then v_product.unit_type else null end;
  v_gtin:=case
    when v_variant.gtin~'^[0-9]{8,14}$' then v_variant.gtin
    when v_mapping.match_method='gtin' and v_mapping.match_confidence=100 and v_mapping.external_gtin~'^[0-9]{8,14}$' then v_mapping.external_gtin
    else null end;
  v_identity:=jsonb_build_object(
    'identity_version',1,
    'offer_id',v_offer.id::text,
    'retailer_id',v_offer.retailer_id::text,
    'retailer_product_id',v_offer.retailer_product_id::text,
    'product_id',v_offer.product_id::text,
    'product_variant_id',v_offer.product_variant_id::text,
    'external_product_id',v_mapping.external_product_id,
    'external_variant_id',v_mapping.external_variant_id,
    'flavour',coalesce(v_variant.flavour_code,v_variant.flavour_label),
    'size_value',public.atomic_import_decimal_string(v_variant.size_value),
    'size_unit',v_variant.size_unit,
    'pack_count',v_variant.pack_count::text,
    'product_format',coalesce(v_variant.product_format,v_product.product_format),
    'unit_count',case when v_unit_count is null then null else to_jsonb(v_unit_count::text) end,
    'unit_type',v_unit_type,
    'gtin',v_gtin,
    'retailer_source',v_retailer.slug,
    'source_importer',p_source_importer,
    'currency','GBP');
  v_fingerprint:=public.retailer_catalogue_sha256_json(v_identity);

  insert into public.price_identity_series(
    identity_version,fingerprint,offer_id,retailer_id,retailer_product_id,product_id,product_variant_id,
    external_product_id,external_variant_id,flavour,size_value,size_unit,pack_count,product_format,
    unit_count,unit_type,gtin,retailer_source,source_importer,currency)
  values(1,v_fingerprint,v_offer.id,v_offer.retailer_id,v_offer.retailer_product_id,v_offer.product_id,v_offer.product_variant_id,
    v_mapping.external_product_id,v_mapping.external_variant_id,coalesce(v_variant.flavour_code,v_variant.flavour_label),
    v_variant.size_value,v_variant.size_unit,v_variant.pack_count,coalesce(v_variant.product_format,v_product.product_format),
    v_unit_count,v_unit_type,v_gtin,v_retailer.slug,p_source_importer,'GBP')
  on conflict(fingerprint) do nothing;
  select id into v_series_id from public.price_identity_series where fingerprint=v_fingerprint;

  if exists(select 1 from public.price_identity_series where offer_id=v_offer.id and id<>v_series_id) then
    v_flags:=array_append(v_flags,'IDENTITY_SERIES_RESET');
  end if;
  select * into v_previous from public.price_history
    where identity_series_id=v_series_id and (p_existing_history_id is null or id<>p_existing_history_id)
    order by checked_at desc,id desc limit 1;
  if v_previous.id is not null then
    if abs(v_offer.total_price-v_previous.total_price)>=100 then v_flags:=array_append(v_flags,'LARGE_ABSOLUTE_CHANGE'); end if;
    if v_previous.total_price>0 and abs(v_offer.total_price-v_previous.total_price)/v_previous.total_price>=0.5 then v_flags:=array_append(v_flags,'LARGE_PERCENT_CHANGE'); end if;
    if v_previous.in_stock=false and v_offer.in_stock=true then v_flags:=array_append(v_flags,'RETURNED_FROM_OOS'); end if;
    select * into v_previous_two from public.price_history
      where identity_series_id=v_series_id and id<>v_previous.id and (p_existing_history_id is null or id<>p_existing_history_id)
      order by checked_at desc,id desc limit 1;
    if v_previous_two.id is not null and round(v_previous_two.total_price,2)=round(v_offer.total_price,2)
       and round(v_previous.total_price,2)<>round(v_offer.total_price,2)
       and v_offer.last_checked_at-v_previous.checked_at<=interval '48 hours' then
      v_flags:=array_append(v_flags,'RAPID_REVERSAL');
    end if;
  end if;
  select coalesce(array_agg(distinct flag order by flag),'{}') into v_flags from unnest(v_flags) flag;
  v_status:=case when cardinality(v_flags)>0 then 'quarantined' else 'proven' end;

  if p_existing_history_id is not null then
    update public.price_history set
      identity_series_id=v_series_id,currency='GBP',in_stock=v_offer.in_stock,observation_kind=p_observation_kind,
      source_run_id=p_source_run_id,source_importer=p_source_importer,recorder_version=1,
      observation_date=(v_offer.last_checked_at at time zone 'UTC')::date,evidence_status=v_status,anomaly_flags=v_flags
    where id=p_existing_history_id and offer_id=v_offer.id and identity_series_id is null
      and price is not distinct from v_offer.price and shipping_cost is not distinct from v_offer.shipping_cost
      and total_price is not distinct from v_offer.total_price and checked_at is not distinct from v_offer.last_checked_at
    returning id into v_history_id;
    if v_history_id is null then return jsonb_build_object('status','IDENTITY_OBSERVATION_SKIPPED','reason','CURRENT_HISTORY_ROW_MISMATCH'); end if;
  else
    insert into public.price_history(offer_id,price,shipping_cost,total_price,checked_at,identity_series_id,currency,in_stock,
      observation_kind,source_run_id,source_importer,recorder_version,observation_date,evidence_status,anomaly_flags)
    values(v_offer.id,v_offer.price,v_offer.shipping_cost,v_offer.total_price,v_offer.last_checked_at,v_series_id,'GBP',v_offer.in_stock,
      p_observation_kind,p_source_run_id,p_source_importer,1,(v_offer.last_checked_at at time zone 'UTC')::date,v_status,v_flags)
    on conflict do nothing returning id into v_history_id;
    if v_history_id is null then
      select id into v_history_id from public.price_history
      where identity_series_id=v_series_id and (
        (source_importer=p_source_importer and source_run_id=p_source_run_id and observation_kind=p_observation_kind)
        or (observation_kind='daily_confirmation' and p_observation_kind='daily_confirmation' and observation_date=(v_offer.last_checked_at at time zone 'UTC')::date)
      ) order by id limit 1;
      return jsonb_build_object('status','IDENTITY_OBSERVATION_REPLAYED','price_history_id',v_history_id::text,'identity_series_id',v_series_id::text,'fingerprint',v_fingerprint);
    end if;
  end if;
  return jsonb_build_object('status','IDENTITY_OBSERVATION_RECORDED','price_history_id',v_history_id::text,
    'identity_series_id',v_series_id::text,'fingerprint',v_fingerprint,'evidence_status',v_status,'anomaly_flags',to_jsonb(v_flags));
end
$recorder$;

create or replace function public.retailer_catalogue_business_counts()
returns jsonb language sql stable security definer set search_path=pg_catalog,public,pg_temp as $counts$
  select jsonb_build_object(
    'products',(select count(*) from public.products),
    'product_variants',(select count(*) from public.product_variants),
    'retailer_products',(select count(*) from public.retailer_products),
    'offers',(select count(*) from public.offers),
    'price_history',(select count(*) from public.price_history where observation_kind is distinct from 'daily_confirmation'))
$counts$;

create or replace function public.apply_approved_product_import_plan(
  p_approval_id uuid,p_artifact_sha256 text,p_plan_fingerprint text,p_source_row_fingerprint text,
  p_retailer_id bigint,p_plan_kind text,p_run_id text) returns jsonb
language plpgsql volatile security definer set search_path=pg_catalog,public,pg_temp as $apply_approved$
declare
  v_approval public.approved_import_plans%rowtype;
  v_result jsonb;
  v_consumed_at timestamptz;
  v_observation jsonb;
  v_kind text;
begin
  select * into v_approval from public.approved_import_plans where id=p_approval_id for update;
  if not found then raise exception 'approved import plan not found'; end if;
  if v_approval.status<>'approved' or v_approval.consumed_at is not null then raise exception 'approved import plan already consumed'; end if;
  if v_approval.expires_at<=now() then raise exception 'approved import plan expired'; end if;
  if v_approval.artifact_sha256 is distinct from p_artifact_sha256 or v_approval.run_id is distinct from p_run_id
     or v_approval.plan_fingerprint is distinct from p_plan_fingerprint or v_approval.source_row_fingerprint is distinct from p_source_row_fingerprint
     or v_approval.retailer_id is distinct from p_retailer_id or v_approval.plan_kind is distinct from p_plan_kind then
    raise exception 'approved import plan metadata mismatch';
  end if;
  if v_approval.plan_fingerprint is distinct from v_approval.plan_json#>>'{meta,plan_fingerprint}'
     or v_approval.source_row_fingerprint is distinct from v_approval.plan_json#>>'{meta,source_row_fingerprint}'
     or v_approval.plan_kind is distinct from v_approval.plan_json#>>'{meta,plan_kind}'
     or v_approval.retailer_id is distinct from nullif(v_approval.plan_json#>>'{retailer,id}','')::bigint
     or md5(public.atomic_import_canonical_json(jsonb_set(v_approval.plan_json,'{meta,plan_fingerprint}','null'::jsonb,false)))<>v_approval.plan_fingerprint then
    raise exception 'approved import plan ledger integrity mismatch';
  end if;
  v_result:=public.apply_product_import_plan(v_approval.plan_json);
  v_kind:=case
    when v_result->>'offer_action'='create' then 'offer_created'
    when v_result->>'price_history_action'='create' then 'delivered_price_changed'
    else 'daily_confirmation' end;
  v_observation:=public.record_identity_proven_price_observation(
    (v_result->>'offer_id')::bigint,v_kind,v_approval.run_id,v_approval.source,
    nullif(v_result->>'price_history_id','')::bigint);
  if v_observation->>'status'='IDENTITY_OBSERVATION_RECORDED'
     and v_result->>'price_history_id' is null then
    v_result:=jsonb_set(v_result,'{price_history_id}',to_jsonb((v_observation->>'price_history_id')::bigint),true);
  end if;
  update public.approved_import_plans
    set status='consumed',consumed_at=now(),identity_observation_result=v_observation
    where id=v_approval.id returning consumed_at into v_consumed_at;
  return v_result||jsonb_build_object('approval_id',v_approval.id,'approval_status','consumed','consumed_at',v_consumed_at,
    'artifact_sha256',v_approval.artifact_sha256,'run_id',v_approval.run_id,'plan_fingerprint',v_approval.plan_fingerprint,
    'source_row_fingerprint',v_approval.source_row_fingerprint,'retailer_id',v_approval.retailer_id::text,'plan_kind',v_approval.plan_kind,
    'identity_observation',v_observation);
end
$apply_approved$;

