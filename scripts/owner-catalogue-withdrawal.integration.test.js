function loadPublicModule(relative, supabase, cache = new Map()) {
  const filename = path.resolve(ROOT, relative);
  if (cache.has(filename)) return cache.get(filename);
  const exports = {}; cache.set(filename, exports);
  const localRequire = name => {
    if (name === "server-only") return {};
    if (name === "next/cache") return { unstable_cache: read => read };
    if (/\/supabaseAdmin$/.test(name)) return { supabaseAdmin: supabase };
    if (/\/supabase$/.test(name)) return { supabase };
    if (!name.startsWith(".")) return require(name);
    const resolved = path.resolve(path.dirname(filename), name);
    if (fs.existsSync(`${resolved}.ts`)) return loadPublicModule(path.relative(ROOT, `${resolved}.ts`), supabase, cache);
    return require(resolved);
  };
  const output = ts.transpileModule(fs.readFileSync(filename, "utf8"), { fileName: filename,
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  vm.runInNewContext(output, { exports, require: localRequire, URL, Date, process, console, Buffer });
  return exports;
}

function publicSqlAdapter(read) {
  return { from(table) {
    assert.ok(["products", "product_variants", "offers", "retailers", "nutrition_candidates"].includes(table), table);
    const filters = []; let offset = 0, limit = 10000;
    const column = key => { assert.match(key, /^[a-z_]+$/); return `x.${ident(key)}`; };
    const execute = async () => {
      const where = filters.length ? `where ${filters.join(" and ")}` : "";
      const rows = read(`select to_jsonb(x) ${table === "products" ? "||jsonb_build_object('offers',(select coalesce(jsonb_agg(to_jsonb(o)||jsonb_build_object('retailer',(select to_jsonb(r) from retailers r where r.id=o.retailer_id))),'[]'::jsonb) from offers o where o.product_id=x.id))" : ""} value from ${ident(table)} x ${where} order by x.id limit ${limit} offset ${offset}`);
      return { data: rows.map(r => r.value), count: read(`select count(*)::int value from ${ident(table)} x ${where}`)[0].value, error: null };
    };
    const builder = { select() { return builder; },
      eq(key, value) { filters.push(`${column(key)}=${q(value)}`); return builder; },
      is(key, value) { assert.equal(value, null); filters.push(`${column(key)} is null`); return builder; },
      not(key, operation, value) { assert.equal(operation, "is"); assert.equal(value, null); filters.push(`${column(key)} is not null`); return builder; },
      in(key, values) { filters.push(values.length ? `${column(key)} in (${values.map(q)})` : "false"); return builder; },
      or(value) {
        const clauses = value.split(",").map(part => {
          const match = part.match(/^([a-z_]+)\.ilike\.(.+)$/); assert.ok(match, `Unsupported public test predicate ${part}`);
          return `${column(match[1])} ilike ${q(match[2].replace(/^"|"$/g,""))}`;
        }); filters.push(`(${clauses.join(" or ")})`); return builder;
      },
      order() { return builder; }, range(from, to) { offset = from; limit = to - from + 1; return builder; },
      limit(value) { limit = value; return builder; },
      then(resolve, reject) { return execute().then(resolve, reject); },
    };
    return builder;
  } };
}

