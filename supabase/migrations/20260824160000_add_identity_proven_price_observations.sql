create table public.price_identity_series (
  id bigint generated by default as identity primary key,
  identity_version smallint not null check(identity_version=1),
  fingerprint text not null unique check(fingerprint~'^[0-9a-f]{64}$'),
  offer_id bigint not null check(offer_id>0),
  retailer_id bigint not null check(retailer_id>0),
  retailer_product_id bigint not null check(retailer_product_id>0),
  product_id bigint not null check(product_id>0),
  product_variant_id bigint not null check(product_variant_id>0),
  external_product_id text not null check(length(trim(external_product_id)) between 1 and 128),
  external_variant_id text check(external_variant_id is null or length(trim(external_variant_id)) between 1 and 128),
  flavour text,
  size_value numeric not null check(size_value>0 and size_value::text<>'NaN'),
  size_unit text not null check(length(trim(size_unit)) between 1 and 32),
  pack_count integer not null check(pack_count>0),
  product_format text,
  unit_count integer check(unit_count is null or unit_count>0),
  unit_type text check(unit_type is null or length(trim(unit_type)) between 1 and 64),
  gtin text check(gtin is null or gtin~'^[0-9]{8,14}$'),
  retailer_source text not null check(retailer_source~'^[a-z0-9][a-z0-9-]{0,127}$'),
  source_importer text not null check(source_importer~'^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'),
  currency text not null check(currency='GBP'),
  created_at timestamptz not null default clock_timestamp(),
  constraint price_identity_series_unit_pair check((unit_count is null)=(unit_type is null))
);

comment on table public.price_identity_series is
